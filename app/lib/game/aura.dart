/// Аура на ударе дуэли: чья и началась ли сейчас.
class AuraMark {
  const AuraMark({
    required this.attacker,
    required this.kind,
    this.start = false,
  });

  final bool attacker;
  final AuraKind kind;
  final bool start;
}
